import { writeFileSync } from "node:fs";
import { cards } from "../src/data/learn/index.ts";

const map = {};
for (const card of cards) {
  for (const t of card.topics) {
    map[t.id] = [t.title, ...t.body, t.why ?? ""].filter(Boolean).join("\n\n").slice(0, 4000);
  }
}
writeFileSync(
  "worker/src/topics.generated.ts",
  `/* GENERATED by scripts/gen-worker-topics.mjs. Do not edit.\n` +
    `   Run: npm run gen:topics  (also runs as part of the worker deploy) */\n\n` +
    `export const TOPICS: Record<string, string> = ${JSON.stringify(map, null, 0)};\n`,
);
console.log(`wrote ${Object.keys(map).length} topics`);
