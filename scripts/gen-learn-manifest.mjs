/* The learn index, without the learn material.
 *
 * Every card used to arrive in one JavaScript chunk: 407KB raw, 111KB over the
 * wire, on a page that shows one card. Reading about containers downloaded all
 * five case studies, and the ratio was getting worse with every topic written.
 *
 * The fix is not a database. A database would add a network round trip to a
 * page that currently needs none, and would take the text out of the
 * prerendered HTML that search engines and link previews read. The fix is to
 * ship only what the page uses: this manifest for the index, which needs titles
 * and levels, and one module per group of cards, fetched when a card is opened.
 *
 * Generated rather than written, because a hand-maintained index of 34 cards
 * silently stops listing the newest one, and nothing fails when it does.
 */
import { writeFileSync } from "node:fs";

const SITE = "https://sumitgundawar.com";
import { cards } from "../src/data/learn/index.ts";
import { GROUPS } from "../src/data/learn/groups.ts";

const groupOf = new Map();
for (const [group, ids] of Object.entries(GROUPS)) {
  for (const id of ids) groupOf.set(id, group);
}

const missing = cards.filter((c) => !groupOf.has(c.id)).map((c) => c.id);
if (missing.length) {
  console.error(`FAIL  cards missing from GROUPS: ${missing.join(", ")}`);
  process.exit(1);
}

const entries = cards.map((c) => ({
  id: c.id,
  title: c.title,
  summary: c.summary,
  track: c.track,
  group: groupOf.get(c.id),
  topics: c.topics.map((t) => ({ id: t.id, title: t.title, level: t.level })),
}));

const body = `/* Generated by scripts/gen-learn-manifest.mjs. Do not edit.
 *
 * Card titles, summaries and topic levels: everything the index page renders,
 * and none of the material itself. The bodies, diagrams and questions live in
 * one module per group and are fetched when a card is opened.
 */
import type { CardMeta } from "./types";

export const manifest: CardMeta[] = ${JSON.stringify(entries, null, 2)};

export const topicCount = ${entries.reduce((n, c) => n + c.topics.length, 0)};
export const cardCount = ${entries.length};
`;

writeFileSync("src/data/learn/manifest.ts", body);

/* The sitemap is regenerated from the same list, because the two drifted the
   moment a card was added: a page that exists, is linked and is not in the
   sitemap is also not prerendered, so it ships as an empty shell to every
   crawler. Generating both from one source removes the possibility. */
const today = new Date().toISOString().slice(0, 10);
const fixed = [
  ["/", "1.0"],
  ["/learn", "0.9"],
  ["/writing", "0.8"],
  ["/build", "0.8"],
  ["/archive", "0.6"],
];
const urls = [
  ...fixed.map(([path, priority]) => `  <url><loc>${SITE}${path}</loc><lastmod>${today}</lastmod><priority>${priority}</priority></url>`),
  ...entries.map((c) => `  <url><loc>${SITE}/learn/${c.id}</loc><lastmod>${today}</lastmod><priority>0.7</priority></url>`),
];
writeFileSync(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`,
);
console.log(`sitemap: ${urls.length} urls`);
console.log(`learn manifest: ${entries.length} cards, ${entries.reduce((n, c) => n + c.topics.length, 0)} topics`);
