import { writeFileSync } from "node:fs";
import { articles } from "../src/data/content.ts";

const picked = [...articles]
  .sort((a, b) => (a.iso < b.iso ? 1 : -1))
  .slice(0, 3)
  .map((a) => ({
    title: a.title,
    url: a.url,
    publication: a.publication,

    hook: (a.summary.split(/(?<=\.)\s/)[0] ?? a.summary).trim(),
  }));

const out = `/* Generated by scripts/gen-worker-articles.mjs. Do not edit.
 * Source: src/data/content.ts. Regenerate with npm run gen:articles. */

export interface FeaturedArticle {
  title: string;
  url: string;
  publication: string;
  hook: string;
}

export const FEATURED: FeaturedArticle[] = ${JSON.stringify(picked, null, 2)};
`;

writeFileSync("worker/src/articles.generated.ts", out);
console.log(`articles: ${picked.length} featured written to worker/src/articles.generated.ts`);
